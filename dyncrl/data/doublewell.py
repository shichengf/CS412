"""Synthetic benchmark for interpretation: a particle in a double-well landscape.

Six latent factors q = (x, z1, z2, z3, u1, u2) follow overdamped Langevin
dynamics. x is the reaction coordinate and the well it occupies defines the
regime. z1, z2 and z3 are themselves bistable and set the depth of the left
well, the depth of the right well and the barrier height of the x potential;
u1 and u2 are uncoupled nuisance factors. Thirty observed variables are
generated by a sparse additive mixing with known supports, so the influence
matrix recovered by the model can be checked against the truth.
"""

import numpy as np

FACTORS = ["x", "z1", "z2", "z3", "u1", "u2"]
DRIVERS = [0, 1, 2]          # factors whose distribution differs between the two regimes
N_OBS = 30
SUPPORTS = {                 # factor -> observed variables it generates
    0: [0, 1, 2, 3, 4],
    1: [5, 6, 7, 8],
    2: [9, 10, 11, 12, 4],   # observation 4 is shared with x
    3: [13, 14, 15, 16, 8],  # observation 8 is shared with z1
    4: [17, 18, 19, 20, 21],
    5: [22, 23, 24, 25, 26, 21],
}                            # observations 27-29 are pure noise
LAG = 2
DT, KT = 0.002, 0.3
X_THRESHOLD = 0.1
OBS_NOISE = 0.05

MIXING = {
    "sin": lambda z, w, phi: w * np.sin(z + phi),
    "tanh": lambda z, w, phi: w * np.tanh(2 * (z + phi)),
    "cubic": lambda z, w, phi: w * (z + phi) ** 3 / 5,
    "sigmoid": lambda z, w, phi: w / (1 + np.exp(-3 * (z + phi))),
    "softplus": lambda z, w, phi: w * np.log(1 + np.exp(2 * (z + phi))) / 2,
}


def _g(q, c, s):
    return np.exp(-(q - c) ** 2 / (2 * s * s))


def _dg(q, c, s):
    return -(q - c) / (s * s) * _g(q, c, s)


def _d_double(q, left, right, depth, barrier, sw, sb, ck):
    mid = (left + right) / 2
    return (-depth * (_dg(q, left, sw) + _dg(q, right, sw))
            + barrier * _dg(q, mid, sb) + 4 * ck * (q - mid) ** 3)


def _d_triple(q, left, mid, right, depth, barrier, sw, sb, ck):
    return (-depth * (_dg(q, left, sw) + _dg(q, mid, sw) + _dg(q, right, sw))
            + barrier * (_dg(q, (left + mid) / 2, sb) + _dg(q, (mid + right) / 2, sb))
            + 4 * ck * (q - (left + right) / 2) ** 3)


def grad_potential(q):
    """Gradient of the total potential for a batch of states q (chains, 6).

    U = U_x(x; z1, z2, z3) + U(z1) + U(z2) + U(z3) + U(u1) + U(u2), with
    U_x = -z1 G(x, -1) - z2 G(x, +1) + z3 G(x, 0) + 0.08 x^4.
    """
    x, z1, z2, z3, u1, u2 = q.T
    d1, d2, bh = np.clip(z1, 0.1, 3.0), np.clip(z2, 0.1, 3.0), np.clip(z3, 0.05, 3.0)
    sw, sb = 0.45, 0.5
    gx = -d1 * _dg(x, -1, sw) - d2 * _dg(x, 1, sw) + bh * _dg(x, 0, sb) + 4 * 0.08 * x ** 3
    gz1 = -_g(x, -1, sw) * ((z1 > 0.1) & (z1 < 3.0)) + _d_double(z1, 0.5, 1.5, 1.0, 0.4, 0.25, 0.3, 0.05)
    gz2 = -_g(x, 1, sw) * ((z2 > 0.1) & (z2 < 3.0)) + _d_double(z2, 0.5, 1.5, 1.0, 0.4, 0.25, 0.3, 0.05)
    gz3 = _g(x, 0, sb) * ((z3 > 0.05) & (z3 < 3.0)) + _d_double(z3, 0.2, 1.2, 1.0, 0.4, 0.25, 0.3, 0.05)
    gu1 = _d_double(u1, -1.0, 1.0, 1.0, 0.5, 0.45, 0.5, 0.08)
    gu2 = _d_triple(u2, -1.0, 0.0, 1.0, 1.0, 0.5, 0.35, 0.25, 0.06)
    return np.stack([gx, gz1, gz2, gz3, gu1, gu2], axis=1)


def simulate(n_chains=32, n_steps=150_000, stride=40, seed=0):
    """Euler-Maruyama Langevin dynamics for several independent chains.

    Half of the chains start in each well. Returns (n_chains, n_steps // stride, 6).
    """
    rng = np.random.default_rng(seed)
    q = np.zeros((n_chains, 6))
    left = np.arange(n_chains) % 2 == 0
    q[:, 0] = np.where(left, -1.0, 1.0)
    q[:, 1] = np.where(left, 1.5, 0.5)
    q[:, 2] = np.where(left, 0.5, 1.5)
    q[:, 3] = 0.7
    q[:, 4] = rng.choice([-1.0, 1.0], n_chains)
    q[:, 5] = rng.choice([-1.0, 0.0, 1.0], n_chains)

    scale = np.sqrt(2 * KT * DT)
    frames = np.empty((n_chains, n_steps // stride, 6))
    for step in range(n_steps):
        q = q - DT * grad_potential(q) + scale * rng.standard_normal(q.shape)
        if (step + 1) % stride == 0:
            frames[:, step // stride] = q
    return frames


def observe(latents, seed=0):
    """Sparse additive mixing: every observation sums a few scalar functions."""
    rng = np.random.default_rng(seed)
    x = np.zeros(latents.shape[:-1] + (N_OBS,))
    names = list(MIXING)
    for j, obs in SUPPORTS.items():
        for i in obs:
            f = MIXING[names[rng.integers(len(names))]]
            x[..., i] += f(latents[..., j], rng.uniform(0.5, 2.0), rng.uniform(-1.0, 1.0))
    return x + OBS_NOISE * rng.standard_normal(x.shape)


def generate(n_chains=32, n_steps=150_000, stride=40, seed=0):
    """Simulate, observe, and cut into windows that stay inside one well.

    Returns x (N, 3, 30), the true latents y (N, 3, 6) and the regime c (N,),
    balanced between the two regimes.
    """
    latents = simulate(n_chains, n_steps, stride, seed)
    obs = observe(latents, seed)
    state = np.where(latents[..., 0] < -X_THRESHOLD, 0, np.where(latents[..., 0] > X_THRESHOLD, 1, -1))

    T = LAG + 1
    idx = np.arange(latents.shape[1] - T + 1)[:, None] + np.arange(T)      # (windows, T)
    win_state = state[:, idx]                                              # (chains, windows, T)
    keep = (win_state[..., 0] >= 0) & (win_state == win_state[..., :1]).all(-1)
    x, y, c = obs[:, idx][keep], latents[:, idx][keep], win_state[..., 0][keep]

    rng = np.random.default_rng(seed)
    n = min((c == 0).sum(), (c == 1).sum())
    pick = np.concatenate([rng.choice(np.flatnonzero(c == k), n, replace=False) for k in (0, 1)])
    return x[pick].astype(np.float32), y[pick].astype(np.float32), c[pick]


def true_influence():
    """Ground-truth support matrix (30 observations by 6 factors) with 0/1 entries."""
    A = np.zeros((N_OBS, len(FACTORS)))
    for j, obs in SUPPORTS.items():
        A[obs, j] = 1.0
    return A
